  /** The line under each disabled control. */
  notReadyNote: string;
  /** Fact labels on a platform card. */
  system: string;
  builtWith: string;
  /** The system requirement where none is decided yet. */
  toBeSet: string;
  macSystem: string;
  macStack: string;
  qtStack: string;
  /** Heading above the downloads that exist today (the Corvus Store files and the model files). */
